export const QUIET = 10;   // modules of white on each side, as scanners need
export const HEIGHT = 40;

/** @param {string} text  @returns {{ bars: [number, number][], width: number }} the bars as [x, width] pairs in modules, and the width of the whole symbol (quiet zones included) */
export function code128(text) {
  const codes = [...text].map((ch) => ch.charCodeAt(0) - 32);
  if (codes.some((c) => c < 0 || c > 95)) throw new Error(`Code 128 B cannot encode "${text}"`);
  const sum = codes.reduce((acc, c, i) => acc + c * (i + 1), 104);
  const bits = [104, ...codes, sum % 103, 106].map((c) => CODE128[c]).join('');
  /** @type {[number, number][]} */
  const bars = [];
  for (let i = 0; i < bits.length;) {
    if (bits[i] !== '1') { i++; continue; }
    let j = i;
    while (bits[j] === '1') j++;
    bars.push([QUIET + i, j - i]);
    i = j;
  }
  return { bars, width: bits.length + QUIET * 2 };
}
