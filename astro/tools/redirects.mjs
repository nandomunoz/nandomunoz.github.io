// The redirects from the old WordPress (soynando.com) to the new site (plan §5, D11), generated from the posts'
// `original` addresses so they cannot drift from the content: a Cloudflare Bulk Redirects list (CSV) and the same 301s as
// an .htaccess for as long as the WordPress hosting is kept. soynando.com is another domain: Astro cannot redirect it,
// whoever serves that domain does. Run after a change to the posts:   npm run redirects
//
// Writes redirects/soynando-bulk-redirects.csv, redirects/soynando.htaccess and redirects/README.md, and checks that
// every target is a page of the built site (run `npm run build` first).
import fs from 'node:fs';
import path from 'node:path';

const root = new URL('../', import.meta.url).pathname;
const NEW = 'https://nandomunoz.com';
const posts = [];
for (const dir of fs.readdirSync(path.join(root, 'src/content/posts'))) {
  const md = fs.readFileSync(path.join(root, 'src/content/posts', dir, 'index.md'), 'utf8');
  const original = md.match(/^original:\s*"?([^"\n]+)"?\s*$/m)?.[1];
  if (!original) throw new Error(`${dir}: no original address in the front matter`);
  posts.push({ slug: dir, from: new URL(original).pathname });
}

const rows = posts.map((p) => [`soynando.com${p.from}`, `${NEW}/blog/${p.slug}/`]);
// the pages of the old site that keep their address, and the feed
rows.push(['soynando.com/politica-de-cookies/', `${NEW}/politica-de-cookies/`], ['soynando.com/privacidad/', `${NEW}/privacidad/`], ['soynando.com/feed/', `${NEW}/rss.xml`],
  ['soynando.com/blog/', `${NEW}/blog/`], ['soynando.com/proyectos/', `${NEW}/proyectos/`],
  // the authors' archives (a WordPress page with nothing the new site has): the home, where the bio is
  ['soynando.com/author/nando-munoz/', `${NEW}/`], ['soynando.com/author/admin/', `${NEW}/`],
  // a post that was published twice: the first version was removed and the one that stays took its slug, so the first
  // version's old address goes there too (the second's comes from its `original`)
  ['soynando.com/introduccion-a-la-ia/', `${NEW}/blog/introduccion-a-la-ia/`]);
// categories and tags, one by one (the inventory of the old site: tools/wp-inventory.mjs). The categories changed their slug;
// the tags kept it (and `historia-de-la-informatica`, `frontend`, `uncategorized` had no posts: they fall to the list).
const WP_CATEGORIES = { 'hablo-de-codigo-y-gestion': 'codigo-y-gestion', 'hablo-de-literatura-y-pensamiento': 'literatura-y-pensamiento' };
for (const [from, to] of Object.entries(WP_CATEGORIES)) rows.push([`soynando.com/category/${from}/`, `${NEW}/blog/categoria/${to}/`]);
for (const t of JSON.parse(fs.readFileSync(path.join(root, 'src/content/tags.json'), 'utf8'))) rows.push([`soynando.com/tag/${t.id}/`, `${NEW}/blog/etiqueta/${t.id}/`]);
// the families last: whatever slug is not above goes to the list
rows.push(['soynando.com/category/', `${NEW}/blog/categoria/`], ['soynando.com/tag/', `${NEW}/blog/etiqueta/`]);

const dup = rows.map((r) => r[0]).filter((s, i, a) => a.indexOf(s) !== i);
if (dup.length) throw new Error(`two posts share an old address: ${[...new Set(dup)].join(', ')}`);

const out = path.join(root, 'redirects');
fs.mkdirSync(out, { recursive: true });
// Cloudflare Bulk Redirects: source_url, target_url, status_code, preserve_query_string, include_subdomains, subpath_matching, preserve_path_suffix
fs.writeFileSync(path.join(out, 'soynando-bulk-redirects.csv'),
  rows.map(([s, t]) => [s, t, 301, 'false', 'true', s.endsWith('/category/') || s.endsWith('/tag/') ? 'true' : 'false', 'false'].join(',')).join('\n') + '\n');
// the same, for Apache (WordPress hosting): exact paths, then the families
fs.writeFileSync(path.join(out, 'soynando.htaccess'), [
  '# soynando.com → nandomunoz.com (generated by tools/redirects.mjs: do not edit)',
  'RewriteEngine On',
  ...rows.filter(([s]) => !/\/(category|tag)\/$/.test(s)).map(([s, t]) => `RewriteRule ^${s.replace('soynando.com/', '').replace(/\/$/, '').replace(/[.+?]/g, '\\$&')}/?$ ${t} [R=301,L]`),
  'RewriteRule ^category/ ' + `${NEW}/blog/categoria/` + ' [R=301,L]',
  'RewriteRule ^tag/ ' + `${NEW}/blog/etiqueta/` + ' [R=301,L]',
  'RewriteRule ^(comments/)?feed/?$ ' + `${NEW}/rss.xml` + ' [R=301,L]',
  '# everything else (wp-content, wp-json, pages that no longer exist): the home',
  'RewriteRule ^ ' + `${NEW}/` + ' [R=301,L]', ''
].join('\n'));
fs.writeFileSync(path.join(out, 'README.md'), `# Redirects from soynando.com

Generated by \`npm run redirects\` from the posts' \`original\` address. soynando.com is another domain than the site, so
these are served by whoever serves soynando.com (plan D11).

## Cloudflare (recommended)

1. Put soynando.com's DNS on Cloudflare (proxied records).
2. **Bulk Redirects** → create a list from \`soynando-bulk-redirects.csv\` (${rows.length} entries: the ${posts.length} posts, the policy pages, the projects, the authors, every category and tag, the feed and the blog;
   \`/category/\` and \`/tag/\` match by prefix) and a Bulk Redirect rule that uses it.
3. A **Redirect Rule** after it for everything else: \`(http.host eq "soynando.com" or http.host eq "www.soynando.com")\` → static \`${NEW}/\`, 301.
4. In Search Console add nandomunoz.com and use *Change of address* from soynando.com.

## Apache (while the WordPress hosting is kept)

Put \`soynando.htaccess\` at the top of soynando.com's \`.htaccess\`, before WordPress' own rules.

## Not covered yet

- Categories and tags are mapped one by one from the inventory of the old site (\`npm run wp:inventory\`); a slug not in the list falls to \`/blog/categoria/\` or \`/blog/etiqueta/\`.
- \`nandomunoz.github.io\` needs nothing here: with nandomunoz.com as the custom domain of the Pages site, GitHub sends it there path and all, and the Cassette's old paths (\`/es/\`, \`/projects/<id>/\`) are pages of the new site that send the visitor on (\`src/lib/legacy.js\`); \`/eastereggs/…\` is published as it was (\`tools/eastereggs.mjs\`).
- Images under \`wp-content/uploads/\` fall to the home.
`);

// every target must be a page of the built site
const bad = [];
for (const [, t] of rows) {
  const p = new URL(t).pathname;
  const file = path.join(root, 'dist', p.endsWith('/') ? p + 'index.html' : p);
  if (!fs.existsSync(file)) bad.push(t);
}
console.log(`✓ ${rows.length} redirects → redirects/`);
if (bad.length) { console.error('✗ targets that do not exist in dist/:\n  ' + bad.join('\n  ')); process.exit(1); }
console.log('✓ every target is a page of the built site');
